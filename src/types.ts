/** API v1 VIEW MODEL: already sanitized and fully resolved by the server.
 * No rule calculation is allowed in this frontend.
 */
export type Side = 'north' | 'south';
export type GameStatus = 'active' | 'finished' | 'paused';
export type ActionGroup = 'deploy' | 'maneuver' | 'recruit' | 'initiative' | 'special' | 'other';
export interface UnitView {
  unit_type: string;
  name: string;
  short_name: string;
  owner_id: string;
  team_id?: string;
  count: number;
  symbol?: string;
}
export interface HexView {
  id: string;
  q: number;
  r: number;
  terrain: 'normal' | 'objective' | 'blocked';
  owner_id: string | null;
  unit: UnitView | null;
  display_label?: string;
  /** Backend-supplied decoration; never used for legality. */
  decoration?: 'pines' | 'rubble' | null;
}
export interface PlayerView {
  id: string;
  side: Side;
  team_id?: string;
  is_ally?: boolean;
  name: string;
  color_name: string;
  control_count: number;
  control_target: number;
  bag_count: number | null;
  discard_count: number | null;
  supply_count: number | null;
  hand_count: number;
  /** Public face-up discard only; facedown coins must never be sent here. */
  faceup_discard?: Array<{unit_type: string; name: string; count: number}>;
  /** Already computed by the engine, not derived from board positions on the client. */
  board_unit_count: number | null;
  is_viewer: boolean;
  /** Public roster; server controls redaction. */
  army: Array<{ unit_type: string; name: string; short_name: string; available: number | null; symbol?: string; description?: string }>;
}
export interface HandCoinView {
  id: string;
  unit_type: string;
  label: string;
  short_name: string;
  symbol?: string;
  is_royal: boolean;
}
export interface ActionView {
  id: string;  // Opaque ID created by the server; the client must not invent one.
  label: string;
  description: string;
  group: ActionGroup;
  payment_coin_type?: string | null;
  source_hex_id?: string | null;
  target_hex_ids?: string[];
  highlight_hex_ids?: string[];
  presentation_icon?: 'move' | 'attack' | 'deploy' | 'shield' | 'recruit' | 'flag' | 'pass' | 'tactic';
  confirm_text?: string;
}
export interface GameEventView {
  id: string;
  time_label: string;
  text: string;
  player_id?: string | null;
  type?: 'move' | 'capture' | 'control' | 'info';
}
export interface GameView {
  schema_version: 1;
  game_id: string;
  revision: number;
  ruleset_label: string;
  status: GameStatus;
  winner_player_id: string | null;
  viewer_player_id: string;
  viewer_team_id?: string;
  winner_team_id?: string | null;
  player_count?: number;
  decision_player_id: string | null;
  initiative_player_id: string | null;
  round: number;
  phase_label: string;
  instruction: string;
  board: HexView[];
  players: PlayerView[];
  /** Only the viewer's own coins. Never include the opponent's hand here. */
  hand: HandCoinView[];
  /** Fully validated choices generated by the rules engine for this viewer only. */
  legal_actions: ActionView[];
  events: GameEventView[];
  server_time?: string;
}
export interface ActionResponse {
  view: GameView;
}
